import { index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import { dataLifecycleAcceptanceRuns, users } from "./schema";

export const documentReleaseAuthorizations = sqliteTable("document_release_authorizations", {
  id: text("id").primaryKey(),
  reference: text("reference").notNull(),
  lifecycleAcceptanceRunId: text("lifecycle_acceptance_run_id").notNull().references(() => dataLifecycleAcceptanceRuns.id, { onDelete: "restrict" }),
  preparedByUserId: text("prepared_by_user_id").notNull().references(() => users.id, { onDelete: "restrict" }),
  clientRequestId: text("client_request_id").notNull(),
  evidenceReference: text("evidence_reference").notNull(),
  rollbackEvidenceReference: text("rollback_evidence_reference").notNull(),
  releaseOwnerUserId: text("release_owner_user_id").notNull().references(() => users.id, { onDelete: "restrict" }),
  monitoringOwnerUserId: text("monitoring_owner_user_id").notNull().references(() => users.id, { onDelete: "restrict" }),
  stopAuthorityUserId: text("stop_authority_user_id").notNull().references(() => users.id, { onDelete: "restrict" }),
  releaseStartsAt: integer("release_starts_at", { mode: "timestamp_ms" }).notNull(),
  releaseEndsAt: integer("release_ends_at", { mode: "timestamp_ms" }).notNull(),
  latestActivationWindowId: text("latest_activation_window_id").notNull(),
  latestAssuranceRunId: text("latest_assurance_run_id").notNull(),
  checkCount: integer("check_count").notNull(),
  passedChecks: integer("passed_checks").notNull(),
  failedChecks: integer("failed_checks").notNull(),
  checkResultsJson: text("check_results_json").notNull(),
  exceptionSignalCount: integer("exception_signal_count").notNull().default(0),
  activeIncidentCount: integer("active_incident_count").notNull().default(0),
  dataMode: text("data_mode").notNull().default("aggregate_only"),
  customerRecordsRead: integer("customer_records_read").notNull().default(0),
  objectsRead: integer("objects_read").notNull().default(0),
  objectsChanged: integer("objects_changed").notNull().default(0),
  externalSystemsContacted: integer("external_systems_contacted").notNull().default(0),
  status: text("status").notNull().default("pending_review"),
  reviewedByUserId: text("reviewed_by_user_id").references(() => users.id, { onDelete: "restrict" }),
  reviewNote: text("review_note"),
  reviewedAt: integer("reviewed_at", { mode: "timestamp_ms" }),
  revokedByUserId: text("revoked_by_user_id").references(() => users.id, { onDelete: "restrict" }),
  revokedAt: integer("revoked_at", { mode: "timestamp_ms" }),
  revocationNote: text("revocation_note"),
  version: integer("version").notNull().default(1),
  createdAt: integer("created_at", { mode: "timestamp_ms" }).notNull(),
  updatedAt: integer("updated_at", { mode: "timestamp_ms" }).notNull(),
}, (table) => [
  uniqueIndex("idx_document_release_reference").on(table.reference),
  uniqueIndex("idx_document_release_request").on(table.preparedByUserId, table.clientRequestId),
  index("idx_document_release_status_window").on(table.status, table.releaseStartsAt, table.releaseEndsAt),
  index("idx_document_release_acceptance_created").on(table.lifecycleAcceptanceRunId, table.createdAt),
]);

export const documentReleaseAuthorizationEvents = sqliteTable("document_release_authorization_events", {
  id: text("id").primaryKey(),
  authorizationId: text("authorization_id").notNull().references(() => documentReleaseAuthorizations.id, { onDelete: "restrict" }),
  actorUserId: text("actor_user_id").notNull().references(() => users.id, { onDelete: "restrict" }),
  action: text("action").notNull(),
  previousStatus: text("previous_status"),
  nextStatus: text("next_status").notNull(),
  codedDetailsJson: text("coded_details_json").notNull(),
  createdAt: integer("created_at", { mode: "timestamp_ms" }).notNull(),
}, (table) => [index("idx_document_release_events_authorization_created").on(table.authorizationId, table.createdAt)]);
